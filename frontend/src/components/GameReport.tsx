import ReactMarkdown from 'react-markdown'

export interface PhaseStats {
  moves: number
  accuracy: number
  inaccuracies: number
  mistakes: number
  blunders: number
}

export interface KeyMoment {
  ply: number
  move_number: string
  san: string
  fen: string
  classification: string
  win_percent_loss: number
  phase: string
  best_move: string
  eval_before: string
  eval_after: string
  tags: string[]
}

export interface OpeningInfo {
  eco: string
  name: string
  book_moves: string[]
  deviation: {
    move_number: string
    san: string
    by: 'user' | 'opponent'
    kind: 'left_theory' | 'end_of_theory'
    theory_moves: string[]
  } | null
}

export interface GameStats {
  analysed_moves: number
  total_user_moves: number
  accuracy: number | null
  classification_counts: Record<string, number>
  phases: Record<string, PhaseStats>
  key_moments: KeyMoment[]
  error_tags: Record<string, number>
  opening?: OpeningInfo | null
}

// The coach's narrative, generated by the LLM after the stats are on screen.
export interface CoachReport {
  text: string | null
  error: string | null
  loading: boolean
}

const PHASE_LABELS: Record<string, string> = {
  opening: 'Abertura',
  middlegame: 'Meio-jogo',
  endgame: 'Final'
}

const COUNT_ROWS: { key: string; label: string; className: string }[] = [
  { key: 'Best Move', label: 'Melhor lance', className: 'great' },
  { key: 'Good Move', label: 'Bom lance', className: 'best' },
  { key: 'Inaccuracy', label: 'Imprecisão', className: 'inaccuracy' },
  { key: 'Mistake', label: 'Erro', className: 'mistake' },
  { key: 'Blunder', label: 'Erro grave', className: 'blunder' }
]

const TAG_LABELS: Record<string, string> = {
  hung_piece: 'peça desprotegida',
  missed_capture: 'captura perdida',
  missed_check: 'xeque perdido',
  missed_mate: 'mate perdido',
  allowed_mate: 'permitiu mate',
  walked_into_tactic: 'caiu em tática'
}

function OpeningCard({ opening }: { opening: OpeningInfo }) {
  const { deviation } = opening
  let theoryNote = 'A partida não saiu da teoria conhecida.'
  if (deviation?.kind === 'end_of_theory') {
    theoryNote = `A teoria conhecida termina em ${deviation.move_number} ${deviation.san}.`
  } else if (deviation) {
    const who = deviation.by === 'user' ? 'Você saiu' : 'O oponente saiu'
    theoryNote = `${who} da teoria em ${deviation.move_number} ${deviation.san} (teoria: ${deviation.theory_moves.join(', ')}).`
  }

  return (
    <div className="report-opening">
      <span>{opening.eco}</span>
      <b>{opening.name}</b>
      <small>{theoryNote}</small>
    </div>
  )
}

interface GameReportProps {
  result: string
  stats: GameStats | null
  statsLoading: boolean
  coach: CoachReport
  message: string | null
  onSelectMoment: (fen: string, ply: number) => void
  onRetry: () => void
  onConfigureLLM: () => void
}

export default function GameReport({
  result,
  stats,
  statsLoading,
  coach,
  message,
  onSelectMoment,
  onRetry,
  onConfigureLLM
}: GameReportProps) {
  return (
    <div className="game-report">
      <span className="eyebrow small">RELATÓRIO DA PARTIDA</span>
      <h2 className="report-result">{result}</h2>

      {message && <p className="message system">{message}</p>}

      {statsLoading && !stats && (
        <p className="message system" style={{ color: '#d0af68' }}>
          🤔 Calculando as estatísticas da partida...
        </p>
      )}

      {stats && (
        <>
          <div className="report-accuracy">
            <span>Precisão</span>
            <b>{stats.accuracy !== null ? `${stats.accuracy}%` : '—'}</b>
            {stats.analysed_moves < stats.total_user_moves && (
              <small>
                {stats.analysed_moves} de {stats.total_user_moves} lances analisados
              </small>
            )}
          </div>

          {stats.opening && <OpeningCard opening={stats.opening} />}

          <div className="report-counts">
            {COUNT_ROWS.map(row => (
              <div key={row.key}>
                <span className={`tag ${row.className}`}>{stats.classification_counts[row.key] ?? 0}</span>
                <span>{row.label}</span>
              </div>
            ))}
          </div>

          {Object.keys(stats.phases).length > 0 && (
            <table className="report-phases">
              <thead>
                <tr><th>Fase</th><th>Lances</th><th>Precisão</th><th>?! / ? / ??</th></tr>
              </thead>
              <tbody>
                {Object.entries(stats.phases).map(([phase, p]) => (
                  <tr key={phase}>
                    <td>{PHASE_LABELS[phase] ?? phase}</td>
                    <td>{p.moves}</td>
                    <td>{p.accuracy}%</td>
                    <td>{p.inaccuracies} / {p.mistakes} / {p.blunders}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}

          {stats.key_moments.length > 0 && (
            <div className="report-moments">
              <span className="eyebrow small">MOMENTOS-CHAVE</span>
              {stats.key_moments.map(km => (
                <button key={km.ply} onClick={() => onSelectMoment(km.fen, km.ply)} title="Ver a posição antes do lance">
                  <b>{km.move_number} {km.san}</b>
                  <span>−{km.win_percent_loss}% · melhor: {km.best_move}</span>
                  {km.tags.length > 0 && (
                    <small>{km.tags.map(t => TAG_LABELS[t] ?? t).join(' · ')}</small>
                  )}
                </button>
              ))}
            </div>
          )}

          {coach.loading && (
            <p className="message system" style={{ color: '#d0af68' }}>🤔 Gerando relatório do treinador...</p>
          )}

          {coach.text && !coach.loading && (
            <div className="message markdown-body">
              <ReactMarkdown>{coach.text}</ReactMarkdown>
            </div>
          )}

          {coach.error && !coach.loading && (
            <div className="report-error">
              <p>⚠️ {coach.error}</p>
              <div>
                <button className="outline-btn" onClick={onConfigureLLM}>Configurar LLM</button>
                <button className="outline-btn" onClick={onRetry}>Gerar novamente</button>
              </div>
            </div>
          )}
        </>
      )}
    </div>
  )
}
